"""Демо-комплект для показа прототипа и автотестов: вымышленная организация «Агросенсор».

    python -m demo.make_demo        → demo/agrosensor/presentation.pdf, spec.docx

Организация, ИНН и цифры вымышлены (ИНН 1234567890 — заведомо не настоящий).
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent / "agrosensor"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

SLIDES = [
    ("АгроСкан-М: беспроводная система мониторинга влажности почвы",
     "ООО «Агросенсор»\nг. Тамбов\nДемонстрационный пример: организация и данные вымышлены"),
    ("Проблема",
     "Хозяйства теряют до 20% урожая из-за неравномерного полива. Агроном объезжает поля вручную и "
     "узнаёт о пересыхании почвы с опозданием на 3–5 дней."),
    ("Решение",
     "АгроСкан-М — сеть автономных датчиков влажности и температуры почвы с передачей данных по LoRaWAN "
     "и веб-платформой, которая строит карту влажности поля и подсказывает, где и когда поливать. "
     "Модель машинного обучения прогнозирует влажность на 72 часа по данным датчиков и метеостанции."),
    ("Преимущества",
     "Датчик работает 3 года без замены батареи — в 2 раза дольше зарубежных аналогов.\n"
     "Отечественная элементная база и серверы в России.\n"
     "Стоимость комплекта на 100 га на 40% ниже импортных систем."),
    ("Результаты пилотов",
     "В 2025 году проведено 3 пилотных внедрения в Тамбовской и Липецкой областях.\n"
     "Экономия воды: 25%\nПрирост урожайности сахарной свёклы: 8%"),
    ("Сотрудничество",
     "Предлагаем поставку комплектов под ключ и пилотное внедрение на 1 сезон.\n"
     "Ищем партнёров для совместной разработки модуля для теплиц.\n"
     "Сайт: https://agrosensor.example  ·  ИНН 1234567890"),
]

SPEC = [
    ("Дальность связи", "до 10 км"),
    ("Срок работы от батареи", "3 года"),
    ("Диапазон измерения влажности", "0–100 %"),
    ("Погрешность измерения влажности", "±2 %"),
    ("Рабочая температура", "от −30 до +60 °C"),
    ("Степень защиты", "IP68"),
    ("Глубина установки", "10–60 см"),
]


def make_pdf(path: Path):
    import pymupdf
    doc = pymupdf.open()
    for title, body in SLIDES:
        page = doc.new_page(width=960, height=540)
        page.insert_font(fontname="dv", fontfile=FONT)
        page.insert_textbox(pymupdf.Rect(60, 50, 900, 160), title, fontname="dv", fontsize=30)
        page.insert_textbox(pymupdf.Rect(60, 170, 900, 520), body, fontname="dv", fontsize=20)
    doc.save(path)


def make_docx(path: Path):
    from docx import Document
    d = Document()
    d.add_heading("Технические характеристики системы АгроСкан-М", 1)
    d.add_paragraph("Система состоит из датчиков почвы АС-1, шлюза LoRaWAN и веб-платформы. "
                    "Уровень готовности технологии — TRL 7: система прошла опытную эксплуатацию в реальных условиях.")
    t = d.add_table(rows=0, cols=2)
    for name, value in SPEC:
        r = t.add_row().cells
        r[0].text, r[1].text = name, value
    d.add_heading("Требования к внедрению", 2)
    d.add_paragraph("Для работы нужен один шлюз на каждые 500 га и доступ шлюза в интернет (GSM или Ethernet). "
                    "Монтаж датчиков на 100 га занимает 2 рабочих дня; ввод в эксплуатацию — до 2 недель.")
    d.save(path)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    make_pdf(OUT / "presentation.pdf")
    make_docx(OUT / "spec.docx")
    print("готово:", *sorted(p.name for p in OUT.iterdir()))


if __name__ == "__main__":
    main()
